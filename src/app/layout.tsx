import "~/styles/globals.css";

import { Inter, Lato, Barlow_Condensed, Lora } from "next/font/google";

import { TRPCReactProvider } from "~/trpc/react";
import { ColorModeProvider } from "~/providers/ColorModeProvider";
import { PHProvider } from "~/providers/PostHogProvider";
import PostHogPageView from "./PostHogPageView";
import SessionProvider from "~/providers/SessionProvider";
import { getServerAuthSession } from "./api/auth/[...nextauth]/route";

// display: swap allows font to default to inter
const inter = Inter({
  subsets: ["latin"],
  variable: "--font-sans",
  display: "swap",
});

const goudy = Lora({
  weight: "700",
  subsets: ["latin"],
  variable: "--font-fancy",
  display: "swap",
});

const lato = Lato({
  weight: ["400", "700"],
  subsets: ["latin"],
  variable: "--button-font",
  display: "swap",
});

const barlow_condensed = Barlow_Condensed({
  weight: "400",
  subsets: ["latin"],
  variable: "--stat-font",
  display: "swap",
});

export const metadata = {
  title: "Create T3 App",
  description: "Generated by create-t3-app",
  icons: [{ rel: "icon", url: "/favicon.ico" }],
};

export default async function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  const session = await getServerAuthSession();
  return (
    <html
      lang="en"
      className={`${inter.className} ${lato.variable} ${barlow_condensed.variable} ${goudy.variable}`}
    >
      <PHProvider>
        <body>
          <PostHogPageView />
          <SessionProvider session={session}>
            <TRPCReactProvider>
              <ColorModeProvider>{children}</ColorModeProvider>
            </TRPCReactProvider>
          </SessionProvider>
        </body>
      </PHProvider>
    </html>
  );
}
